# Run: ruby setup.rb [app-folder] [--setup-only]
require "fileutils"
require "rbconfig"
require "rubygems"
$stdout.sync = true

RAILS_VERSION = "8.1.4"
RUBY_EXECUTABLE = RbConfig.ruby
REPOSITORY = File.expand_path(__dir__)
SETUP_ONLY = !!ARGV.delete("--setup-only")
abort "Usage: ruby setup.rb [app-folder] [--setup-only]" if ARGV.length > 1
APP_FOLDER = File.expand_path(ARGV.first || "exp10_app", REPOSITORY)
MARKER = File.join(APP_FOLDER, ".nwt-ruby-setup")

def run(*command)
  puts "> #{command.join(' ')}"
  abort "Command failed. Fix the error above and rerun setup." unless system(*command)
end

abort "Install Ruby+Devkit 3.4 first. See README.md." if Gem::Version.new(RUBY_VERSION) < Gem::Version.new("3.2.0")
if File.exist?(APP_FOLDER)
  abort "Choose an empty app folder: #{APP_FOLDER}" unless File.directory?(APP_FOLDER)
  if !Dir.empty?(APP_FOLDER) && !File.file?(MARKER)
    abort "App folder contains other files. Choose an empty folder: #{APP_FOLDER}"
  end
end

# Prevent inherited settings from selecting another app or enabling native debug builds.
%w[DEBUG BUNDLE_VERBOSE BUNDLE_GEMFILE BUNDLE_FROZEN BUNDLE_DEPLOYMENT BUNDLE_PATH].each { |key| ENV.delete(key) }
ENV["BUNDLE_IGNORE_CONFIG"] = "true"
ENV["BUNDLE_DISABLE_VERSION_CHECK"] = "true"

if Gem.win_platform?
  begin
    require "ruby_installer/runtime"
    RubyInstaller::Runtime.msys2_installation.enable_msys_apps
  rescue LoadError, StandardError => error
    abort "Ruby build tools are unavailable: #{error.message}\nInstall Ruby+Devkit and complete ridk install 1 3."
  end
end

puts "Preparing Rails #{RAILS_VERSION}. Internet is needed for missing dependencies."
if Gem::Specification.find_all_by_name("rails", RAILS_VERSION).empty?
  run(RUBY_EXECUTABLE, "-S", "gem", "install", "rails", "--version", RAILS_VERSION, "--no-document")
  Gem.clear_paths
end
rails_command = Gem.bin_path("railties", "rails", RAILS_VERSION)

FileUtils.mkdir_p(APP_FOLDER)
File.write(MARKER, "Generated by the NWT Ruby setup script.\n")
new_app = !File.file?(File.join(APP_FOLDER, "config", "application.rb"))
if new_app
  run(RUBY_EXECUTABLE, rails_command, "new", APP_FOLDER, "--name=exp10",
      "--minimal", "--no-rc", "--skip-bundle", "--skip-git", "--skip-test",
      "--skip-docker", "--skip-kamal", "--skip-thruster", "--skip-bootsnap",
      "--skip-dev-gems", "--force")
end

student_model = File.join(APP_FOLDER, "app", "models", "student.rb")
if new_app || !File.file?(student_model)
  %w[Gemfile Gemfile.lock].each do |name|
    FileUtils.cp(File.join(REPOSITORY, "ruby_setup", name), File.join(APP_FOLDER, name))
  end
end

Dir.chdir(APP_FOLDER) do
  run(RUBY_EXECUTABLE, "-S", "bundle", "install")
  unless File.file?(student_model)
    run(RUBY_EXECUTABLE, "bin/rails", "generate", "scaffold", "Student", "name:string")
    File.write(student_model, "class Student < ApplicationRecord\n  validates :name, presence: true\nend\n")
    File.write("config/routes.rb", "Rails.application.routes.draw do\n  root 'students#index'\n  resources :students\nend\n")
    File.write("app/controllers/application_controller.rb", "class ApplicationController < ActionController::Base\nend\n")
  end
  run(RUBY_EXECUTABLE, "bin/rails", "db:prepare")
  puts "\nStudent app ready: #{APP_FOLDER}"
  if SETUP_ONLY
    puts "Start it with: cd \"#{APP_FOLDER}\" then ruby bin/rails server -b 127.0.0.1"
  else
    puts "Open http://localhost:3000/students. Stop the server with Ctrl+C."
    exec(RUBY_EXECUTABLE, "bin/rails", "server", "-b", "127.0.0.1")
  end
end
